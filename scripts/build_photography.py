#!/usr/bin/env python3
"""Generate the static photography manifest from repository photography files."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
PHOTO_ROOT = ROOT / "photography"
OUT = ROOT / "js" / "photography-manifest.js"
EXTS = {".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif"}


def is_hidden(relative_path: Path) -> bool:
    return any(part.startswith(".") for part in relative_path.parts)


def normalized_category(relative_path: Path) -> str:
    return relative_path.parts[0].lower() if relative_path.parts else "uncategorized"


def category_label(category: str) -> str:
    return category.replace("-", " ").replace("_", " ").upper()


def category_location(category: str) -> str:
    return category.replace("-", " ").replace("_", " ").title()


def title_from_filename(name: str) -> str:
    stem = Path(name).stem
    stem = re.sub(r"[_-]+", " ", stem)
    stem = re.sub(r"\s+", " ", stem).strip()
    return stem.title() or "Untitled Photograph"

photos = []
categories = set()
if PHOTO_ROOT.exists():
    images = sorted(
        (
            path
            for path in PHOTO_ROOT.rglob("*")
            if path.is_file()
        ),
        key=lambda path: path.relative_to(PHOTO_ROOT).as_posix().casefold(),
    )
    for image in images:
        relative_in_gallery = image.relative_to(PHOTO_ROOT)
        if is_hidden(relative_in_gallery):
            continue
        if image.suffix.lower() not in EXTS:
            continue
        if image.name.lower().startswith("readme"):
            continue

        category = normalized_category(relative_in_gallery)
        title = title_from_filename(image.name)
        rel = image.relative_to(ROOT).as_posix()
        categories.add(category)
        photos.append(
            {
                "title": title,
                "location": category_location(category),
                "category": category,
                "label": category_label(category),
                "description": "A moment captured by Adarsh.",
                "src": rel,
                "alt": title,
            }
        )

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(
    "// Generated by scripts/build_photography.py. Do not edit by hand.\n"
    + "window.PHOTOGRAPHY_CATEGORIES = "
    + json.dumps(sorted(categories), ensure_ascii=False, indent=2)
    + ";\n"
    + "window.PHOTOGRAPHY_MANIFEST = "
    + json.dumps(photos, ensure_ascii=False, indent=2)
    + ";\n",
    encoding="utf-8",
)
print(f"Generated {OUT.relative_to(ROOT)} with {len(photos)} photograph(s) from {PHOTO_ROOT.relative_to(ROOT)}/")
