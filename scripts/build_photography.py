#!/usr/bin/env python3
"""Generate the static photography manifest from photography/<category>/* image files."""
from pathlib import Path
import json, re

ROOT = Path(__file__).resolve().parents[1]
PHOTO_ROOT = ROOT / "photography"
OUT = ROOT / "js" / "photography-manifest.js"
EXTS = {".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif"}

def title_from_filename(name: str) -> str:
    stem = Path(name).stem
    stem = re.sub(r"[_-]+", " ", stem)
    stem = re.sub(r"\s+", " ", stem).strip()
    return stem.title() or "Untitled Photograph"

photos = []
categories = []
if PHOTO_ROOT.exists():
    category_dirs = sorted(p for p in PHOTO_ROOT.iterdir() if p.is_dir() and not p.name.startswith("."))
    categories = [p.name.lower() for p in category_dirs]
    for category_dir in category_dirs:
        category = category_dir.name.lower()
        for image in sorted(category_dir.iterdir()):
            if image.is_file() and image.suffix.lower() in EXTS and not image.name.startswith("."):
                rel = image.relative_to(ROOT).as_posix()
                photos.append({
                    "title": title_from_filename(image.name),
                    "location": category_dir.name.replace("-", " ").replace("_", " ").title(),
                    "category": category,
                    "label": category_dir.name.replace("-", " ").replace("_", " ").upper(),
                    "description": "A moment captured by Adarsh.",
                    "src": rel,
                    "alt": title_from_filename(image.name),
                })

OUT.write_text("// Generated by scripts/build_photography.py. Do not edit by hand.\nwindow.PHOTOGRAPHY_CATEGORIES = " + json.dumps(categories, ensure_ascii=False, indent=2) + ";\nwindow.PHOTOGRAPHY_MANIFEST = " + json.dumps(photos, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
print(f"Generated {OUT.relative_to(ROOT)} with {len(photos)} photograph(s) from {PHOTO_ROOT.relative_to(ROOT)}/")
